/*Array --> for...of
karena adalah urutan data(iterable), karena langsung mengambil elemen/isi data di dalamnya satu persatu dari awal sampai akhir.*/

/*String --> for...of
karena adalah urutan karakter(iterable), karena bisa membaca huruf/karakter satu per satu secara berurutan.*/

/*Object --> for...in
karena adalah urutan properti(non-iterable), for...in diciptakan khusus untuk menelusuri nama-nama kunci (key) dari suatu Object.*/